-- Dropdown lists for the booking form (agents, vendors, packages, inclusions...), seeded from the Google Form.
-- Safe to run more than once. Run in the Supabase SQL editor.

create table if not exists public.booking_options (
  id uuid primary key default gen_random_uuid(),
  category text not null check (category in (
    'agents', 'nationalities', 'tourPackages', 'boatVendors', 'transportVendors',
    'inclusions', 'snorkelingVendors', 'lunchVendors')),
  value text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (category, value)
);

alter table public.booking_options enable row level security;

-- Every approved user (including Booking Staff) can read the lists for the dropdowns.
drop policy if exists booking_options_read on public.booking_options;
create policy booking_options_read on public.booking_options for select to authenticated
  using (public.is_active_user());

-- Only the master admin (GOD) or accounts allowed to edit the catalog can change the lists.
drop policy if exists booking_options_write on public.booking_options;
create policy booking_options_write on public.booking_options for all to authenticated
  using (public.is_god() or public.has_flag('catalog'))
  with check (public.is_god() or public.has_flag('catalog'));

revoke all on public.booking_options from anon;

